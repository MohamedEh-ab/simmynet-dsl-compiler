#!/usr/bin/env python3
"""Regenerate single_header/simmynet_single.cpp from include/simmynet/*.hpp and src/main.cpp.

    python3 scripts/amalgamate.py

The result is a self-contained translation unit (the simmynet_cli program):
    g++ -std=c++17 -O3 -march=native -o simmynet_cli single_header/simmynet_single.cpp
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
ORDER = ["Version", "Common", "algebraic_ring", "MatrixEngine", "AST", "Lexer", "Parser", "Compiler",
         "Runtime", "Interpreter", "WordEval", "Examples"]
LOCAL_INCLUDE = re.compile(r'^\s*#include\s+(?:"[^"]+"|<simmynet/[^>]+>)\s*\n', re.M)


def strip(text: str) -> str:
    return LOCAL_INCLUDE.sub("", text.replace("#pragma once\n", ""))


parts = ["// simmynet_single.cpp - single-file amalgamation of SimmyNet (the simmynet_cli program).\n"
         "// GENERATED by scripts/amalgamate.py from include/simmynet/*.hpp and src/main.cpp: do not edit.\n"
         "// Build: g++ -std=c++17 -O3 -march=native -o simmynet_cli simmynet_single.cpp\n"]
for name in ORDER:
    body = (ROOT / "include" / "simmynet" / f"{name}.hpp").read_text()
    parts.append(f"\n// ===================== simmynet/{name}.hpp =====================\n{strip(body)}")
parts.append("\n// ===================== src/main.cpp =====================\n" + strip((ROOT / "src" / "main.cpp").read_text()))

out = ROOT / "single_header" / "simmynet_single.cpp"
out.write_text("".join(parts))
print(f"wrote {out.relative_to(ROOT)} ({out.stat().st_size} bytes)")
